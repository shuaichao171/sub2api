const (
	openAICodexTicketExtraKeyPrefix  = "codex_turn_ticket:"
	openAICodexAstraMinVersion       = "0.153.4"
	openAICodexTicketStatePrefix     = "gAAAAA"
	openAICodexTicketDefaultModel    = "gpt-6-astra"
	openAICodexTicketDefaultSolModel = "gpt-5.6-sol"
)

// ErrOpenAICodexTicketUnavailable 表示该号该模型没有可用门票（长度按区间校验，
// 见 openAICodexTicketLengthOK），且 fail_closed 禁止裸打业务请求。
var ErrOpenAICodexTicketUnavailable = errors.New("codex turn-state ticket unavailable")

type openAICodexTicket struct {
	AccountID  int64     `json:"account_id"`
	Model      string    `json:"model"`
	State      string    `json:"state"`
	Length     int       `json:"length"`
	CapturedAt time.Time `json:"captured_at"`
	ExpiresAt  time.Time `json:"expires_at"`
}

func openAICodexTicketKey(accountID int64, model string) string {
	return fmt.Sprintf("%d\x00%s", accountID, strings.TrimSpace(model))
}

func openAICodexTicketExtraKey(model string) string {
	return openAICodexTicketExtraKeyPrefix + strings.TrimSpace(model)
}

const (
	// openAICodexTicketMaxConcurrentProbes 限制单周期并发外呼。无票账号很多时
	// （如 300 号 × 2 模型）一次性全打出去会瞬间打满代理出口，且每发探测
	// 都是一次真实账号请求，必须限流。
	openAICodexTicketMaxConcurrentProbes = 8
	// 打不到票的 (账号,模型) 按连败次数指数退避（30s 起步、每败翻倍、封顶
	// 15 分钟），避免每个周期都空转重试、反复触发 GetAccessToken。
	openAICodexTicketProbeBackoffBase     = 30 * time.Second
	openAICodexTicketProbeBackoffMax      = 15 * time.Minute
	openAICodexTicketProbeBackoffShiftCap = 6
)

// 门票长度合理区间。长度本质是 Fernet 密文 base64 的长度，随上游 payload
// 变化（同日内已观测 292 与 312 两种，均为有效票），因此用区间校验代替
// 精确匹配，避免上游调整长度后全网持续 miss。
const (
	openAICodexTicketMinLength = 200
	openAICodexTicketMaxLength = 512
)

// openAICodexTicketLengthOK 校验门票长度是否落在合理区间。
func openAICodexTicketLengthOK(n int) bool {
	return n >= openAICodexTicketMinLength && n <= openAICodexTicketMaxLength
}

// openAICodexTicketProbeThrottle 记录某 (账号,模型) 的连败退避状态。
type openAICodexTicketProbeThrottle struct {
	mu       sync.Mutex
	failures int
	next     time.Time
}

func openAICodexTicketProbeThrottled(raw any, now time.Time) bool {
	t, _ := raw.(*openAICodexTicketProbeThrottle)
	if t == nil {
		return false
	}
	t.mu.Lock()
	defer t.mu.Unlock()
	return now.Before(t.next)
}

// markOpenAICodexTicketProbeResult 命中则清零退避；未命中按连败次数记录
// 下一次允许探测的时间，refresh 周期据此跳过。
func (s *OpenAIGatewayService) markOpenAICodexTicketProbeResult(key string, harvested bool) {
	if s == nil {
		return
	}
	if harvested {
		s.openaiCodexTicketProbeThrottle.Delete(key)
		return
	}
	raw, _ := s.openaiCodexTicketProbeThrottle.LoadOrStore(key, &openAICodexTicketProbeThrottle{})
	t, _ := raw.(*openAICodexTicketProbeThrottle)
	if t == nil {
		return
	}
	t.mu.Lock()
	defer t.mu.Unlock()
	t.failures++
	shift := t.failures - 1
	if shift > openAICodexTicketProbeBackoffShiftCap {
		shift = openAICodexTicketProbeBackoffShiftCap
	}
	backoff := openAICodexTicketProbeBackoffBase * time.Duration(1<<shift)
	if backoff > openAICodexTicketProbeBackoffMax {
		backoff = openAICodexTicketProbeBackoffMax
	}
	t.next = time.Now().Add(backoff)
}

func normalizeOpenAICodexTicketModel(model string) string {
	return strings.TrimSpace(model)
}

func extractOpenAICodexTicketModel(body []byte) string {
	return normalizeOpenAICodexTicketModel(gjson.GetBytes(body, "model").String())
}

func (s *OpenAIGatewayService) openAICodexTicketConfig() config.OpenAICodexTicketConfig {
	cfg := config.OpenAICodexTicketConfig{}
	if s != nil && s.cfg != nil {
		cfg = s.cfg.Gateway.OpenAICodexTicket
	}
	if cfg.TargetLength <= 0 {
		cfg.TargetLength = 292
	}
	if cfg.TTLSeconds <= 0 {
		cfg.TTLSeconds = 3600
	}
	if cfg.RefreshBeforeSeconds <= 0 {
		cfg.RefreshBeforeSeconds = 600
	}
	if cfg.HarvestProbeIntervalSeconds <= 0 {
		cfg.HarvestProbeIntervalSeconds = 6
	}
	if cfg.HarvestAttemptTimeoutSeconds <= 0 {
		cfg.HarvestAttemptTimeoutSeconds = 25
	}
	if len(cfg.Models) == 0 {
		cfg.Models = []string{openAICodexTicketDefaultModel, openAICodexTicketDefaultSolModel}
	}
	return cfg
}

func (s *OpenAIGatewayService) openAICodexTicketGatedModel(model string) bool {
	model = normalizeOpenAICodexTicketModel(model)
	if model == "" || !s.openAICodexTicketEnabled() {
		return false
	}
	for _, item := range s.openAICodexTicketConfig().Models {
		if normalizeOpenAICodexTicketModel(item) == model {
			return true
		}
	}
	return false
}

// OpenAICodexTicketStatus 是给管理端看的门票摘要，不含 state blob。
type OpenAICodexTicketStatus struct {
	Model            string     `json:"model"`
	Length           int        `json:"length,omitempty"`
	Ready            bool       `json:"ready"`
	RemainingSeconds int64      `json:"remaining_seconds"`
	Blocked          bool       `json:"blocked"`
	ExpiresAt        *time.Time `json:"expires_at,omitempty"`
}

func OpenAICodexTicketStatuses(account *Account, cfg config.OpenAICodexTicketConfig, now time.Time) []OpenAICodexTicketStatus {
	if !cfg.Enabled || !isOpenAICodexTicketAccount(account) {
		return nil
	}
	models := cfg.Models
	if len(models) == 0 {
		models = []string{openAICodexTicketDefaultModel, openAICodexTicketDefaultSolModel}
	}
	out := make([]OpenAICodexTicketStatus, 0, len(models))
	for _, model := range models {
		model = normalizeOpenAICodexTicketModel(model)
		if model == "" {
			continue
		}
		status := OpenAICodexTicketStatus{Model: model}
		ticket := parseOpenAICodexTicketFromAny(0, model, nil)
		if account != nil && account.Extra != nil {
			ticket = parseOpenAICodexTicketFromAny(account.ID, model, account.Extra[openAICodexTicketExtraKey(model)])
		}
		if ticket.valid(now) {
			status.Ready = true
			status.Length = ticket.Length
			remaining := int64(ticket.ExpiresAt.Sub(now) / time.Second)
			if remaining < 0 {
				remaining = 0
			}
			status.RemainingSeconds = remaining
			exp := ticket.ExpiresAt
			status.ExpiresAt = &exp
		}
		status.Blocked = cfg.FailClosed && !status.Ready
		out = append(out, status)
	}
	return out
}

func (s *OpenAIGatewayService) openAICodexTicketEnabled() bool {
	return s.openAICodexTicketEnabledContext(context.Background())
}

func (s *OpenAIGatewayService) openAICodexTicketEnabledContext(ctx context.Context) bool {
	if s == nil {
		return false
	}
	fallback := s.cfg != nil && s.cfg.Gateway.OpenAICodexTicket.Enabled
	if s.settingService != nil {
		return s.settingService.GetOpenAICodexTicketEnabled(ctx, fallback)
	}
	return fallback
}

